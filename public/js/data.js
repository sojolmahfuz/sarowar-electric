// Helper to fix image relative path for any host/subfolder
function fixAssetUrl(url) {
  if (!url) return 'images/fb/logo.jpg';
  if (url.startsWith('http://') || url.startsWith('https://') || url.startsWith('data:')) return url;
  return url.replace(/^\//, '');
}

